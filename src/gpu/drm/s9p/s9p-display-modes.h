static const struct s9p_display_mode *s9p_display_mode_find(unsigned int w,
                                                          unsigned int h)
{
    unsigned int i;
    for (i = 0; i < sizeof(s9p_display_modes) / sizeof(s9p_display_modes[0]); i++)
        if (s9p_display_modes[i].width == w && s9p_display_modes[i].height == h)
            return &s9p_display_modes[i];
    return NULL;
}

/* The panel PPS describes both slices. Each hardware encoder describes half
 * the picture width, and uses Samsung's encoder-only decode delay of 0x1b4.
 * All other words match the panel table, including RC range parameters.
 */
static u32 s9p_encoder_pps_word(const struct s9p_display_mode *mode,
                              unsigned int offset)
{
    u32 value = ((u32)mode->pps[offset] << 24) |
                ((u32)mode->pps[offset + 1] << 16) |
                ((u32)mode->pps[offset + 2] << 8) |
                mode->pps[offset + 3];
    if (offset == 8)
        value = ((mode->width / 2) << 16) | mode->slice_height;
    if (offset == 16)
        value = (value & 0xffff0000) | 0x01b4;
    return value;
}
